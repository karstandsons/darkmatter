#!/usr/bin/env bash
# Vendor Omarchy's base themes (colors.toml only) into the omarchy-theme crate
# and regenerate src/bundled.rs. Run after an Omarchy release adds or changes themes.
#   dev/sync-omarchy-themes.sh [omarchy-themes-dir]   (default: /usr/share/omarchy/themes)
set -euo pipefail

src=${1:-/usr/share/omarchy/themes}
crate=$(cd "$(dirname "$0")/../crates/omarchy-theme" && pwd)
dest=$crate/themes
out=$crate/src/bundled.rs

[[ -d $src ]] || { echo "no themes at $src" >&2; exit 1; }

find "$dest" -mindepth 1 -maxdepth 1 -type d -exec rm -rf {} +
slugs=()
for dir in "$src"/*/; do
  slug=$(basename "$dir")
  [[ -f $dir/colors.toml ]] || { echo "skip $slug: no colors.toml" >&2; continue; }
  mkdir -p "$dest/$slug"
  cp "$dir/colors.toml" "$dest/$slug/colors.toml"
  slugs+=("$slug")
done

{
  echo "// Generated by dev/sync-omarchy-themes.sh from Omarchy's base themes. Do not edit."
  echo "// Omarchy is MIT licensed; see themes/LICENSE."
  echo
  echo "/// (slug, colors.toml) for every bundled Omarchy base theme."
  echo "pub const BUNDLED: &[(&str, &str)] = &["
  for slug in "${slugs[@]}"; do
    echo "    (\"$slug\", include_str!(\"../themes/$slug/colors.toml\")),"
  done
  echo "];"
} > "$out"
echo "bundled ${#slugs[@]} themes from $src"
